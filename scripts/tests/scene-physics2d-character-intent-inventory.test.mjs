import '../adapters/node-studio-core.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { captureBuildSnapshot } from '../adapters/node-build-snapshot.mjs';
import { generateGodotPhysicsCharacterIntentProject, godotPhysicsCharacterIntentAssemblyScripts } from '../backends/godot4-physics-character-intent.mjs';
import { hookCharacterIntent } from '../backends/godot4-physics-character-intent-transform.mjs';
import { generateGodotAudioRequestsProject } from '../backends/godot4-audio-requests.mjs';
import { scenePhysics2DCharacterMotionAuthor } from './helpers/scene-physics2d-character-motion-author-fixture.mjs';
import { scenePhysics2DPlatformMotionAuthor } from './helpers/scene-physics2d-platform-motion-author-fixture.mjs';

async function fixture(t, { platform = false, controls = 'none' } = {}) {
  const f = platform ? await scenePhysics2DPlatformMotionAuthor(t, { consumers: false }) : await scenePhysics2DCharacterMotionAuthor(t, { controls });
  if (platform) await f.edit('documents/scenes/demo.json', scene => { scene.actors[0].controls = controls; });
  const captured = await captureBuildSnapshot(f.author, f.assemblyId);
  assert.equal(captured.ok, true, JSON.stringify(captured.diagnostics));
  const generated = await generateGodotPhysicsCharacterIntentProject(captured.plan);
  const directory = await fs.mkdtemp(path.join(f.temporary, 'intent-inventory-'));
  for (const [name, bytes] of generated.files) {
    await fs.mkdir(path.dirname(path.join(directory, name)), { recursive: true });
    await fs.writeFile(path.join(directory, name), bytes);
  }
  return { f, captured, generated, directory, id: captured.plan.scenes.find(s => s.physics).scene.objectId };
}

test('ineligible project keeps every historical generated byte and backend identity', async t => {
  const { captured, generated, directory } = await fixture(t, { controls: 'arrows' });
  const old = await generateGodotAudioRequestsProject(captured.plan);
  assert.deepEqual([...generated.files], [...old.files]);
  assert.deepEqual(generated.backend, old.backend);
  assert.ok(await godotPhysicsCharacterIntentAssemblyScripts(directory));
});

for (const platform of [false, true]) test(`eligible ${platform ? 'moving one-way platform' : 'ordinary motor'} validates full inventory and rejects tampering`, async t => {
  const { generated, directory, id } = await fixture(t, { platform });
  assert.equal(generated.backend.version, '0.37.0');
  assert.ok(generated.backend.capabilities.includes('physics.character-intent2d'));
  assert.ok(await godotPhysicsCharacterIntentAssemblyScripts(directory));
  const targets = ['character-intent-project.json', 'movement-contacts-helper.gd', 'character-intent-helper.gd',
    'character-intent-port.gd', 'character-intent-original-contacts.gd', `scenes/${id}/runtime.gd`,
    `scenes/${id}/character-intent-original-runtime.gd.txt`];
  if (platform) targets.push(`scenes/${id}/one-way-original.gd`, `scenes/${id}/character-intent-original-one-way-original.gd.txt`);
  for (const name of targets) {
    const file = path.join(directory, name), original = await fs.readFile(file);
    await fs.writeFile(file, Buffer.concat([original, Buffer.from('\n# altered\n')]));
    await assert.rejects(godotPhysicsCharacterIntentAssemblyScripts(directory), { errorCode: 'build_physics_character_intent_invalid' }, name);
    await fs.writeFile(file, original);
  }
  assert.ok(await godotPhysicsCharacterIntentAssemblyScripts(directory));
});

for (const platform of [false, true]) test(`paired runtime and backup tampering is rejected (${platform ? 'platform' : 'motor'})`, async t => {
  const { directory, id } = await fixture(t, { platform });
  const backupFile = path.join(directory, `scenes/${id}/character-intent-original-runtime.gd.txt`);
  const runtimeFile = path.join(directory, `scenes/${id}/runtime.gd`);
  const forged = (await fs.readFile(backupFile, 'utf8')) + '\n# forged original and runtime\n';
  await fs.writeFile(backupFile, forged);
  await fs.writeFile(runtimeFile, hookCharacterIntent(forged));
  await assert.rejects(godotPhysicsCharacterIntentAssemblyScripts(directory), { errorCode: 'build_physics_character_intent_invalid' });
});
