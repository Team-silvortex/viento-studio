import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { backendProjectFixture } from './helpers/backend-project-fixture.mjs';
import { createExecutionBackendRegistry } from '../adapters/node-execution-backends.mjs';
import { readFrozenProjectBuild, runProjectBuild } from '../adapters/node-project-build.mjs';
import { inspectBackendProject, inspectBackendProjectForCleanup } from '../adapters/node-backend-project.mjs';

// Adding a host physics implementation changes its execution admission identity.
// This is distinct from preserving old no-physics author plans/generated bytes.
test('old nonphysical snapshots remain readable but a changed execution adapter requires rebuilding before run or verified export', async t => {
  const f = await backendProjectFixture(t, { version: 2 });
  assert.equal(Object.hasOwn(f.captured.plan, 'physics'), false);
  const changedHash = f.build.executionAdapter.sha256 === 'a'.repeat(64) ? 'b'.repeat(64) : 'a'.repeat(64);
  let toolCalls = 0;
  const registry = createExecutionBackendRegistry([{ ...f.adapter,
    async fingerprint() { return { ...f.build.executionAdapter, sha256: changedHash }; },
    async identify() { toolCalls++; throw new Error('A changed adapter must refuse before tool identification.'); },
    async executePhase() { toolCalls++; throw new Error('A changed adapter must refuse before execution.'); },
  }]);
  await fs.rm(f.author, { recursive: true });
  const frozen = await readFrozenProjectBuild(f.directory, { backendRegistry: registry });
  assert.deepEqual(frozen.plan, f.captured.plan);
  const generated = await registry.resolve(f.adapter.descriptor.id).generate(frozen.plan);
  assert.equal(generated.backend.sha256, f.build.backend.sha256);
  assert.equal(generated.backend.protocolVersion, f.build.backend.protocolVersion);
  const run = await runProjectBuild({ buildDirectory: f.directory, backendRegistry: registry, tool: '/unused-executable' });
  assert.equal(run.ok, false); assert.equal(run.diagnostics[0].code, 'runtime_adapter_changed'); assert.equal(toolCalls, 0);
  await assert.rejects(fs.stat(path.join(f.directory, 'sessions')), { code: 'ENOENT' });
  await assert.rejects(inspectBackendProject({ buildDirectory: f.directory, backendRegistry: registry, ...f.pins }), { errorCode: 'backend_project_changed' });
  const cleanup = await inspectBackendProjectForCleanup({ buildDirectory: f.directory, ...f.pins });
  assert.deepEqual(cleanup.project, f.project); assert.equal(cleanup.inspection.complete, true);
});
