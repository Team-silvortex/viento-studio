import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { GODOT4_EXECUTION_ADAPTER as adapter } from '../backends/godot4-adapter.mjs';
import { validateGodotCamera2DInventory } from '../backends/godot4-camera2d-inventory.mjs';
import { cameraProject, cameraOn, cameraStage } from './helpers/godot-camera2d-fixture.mjs';
const invalid = { errorCode: 'build_camera2d_inventory_invalid' };
function bounded(plan, index, camera) {
  cameraOn(plan, index, camera); plan.scenes[index].camera2d.document.schemaVersion = 2;
  for (const owner of [plan, plan.scenes[index]]) owner.requiredCapabilities = [...new Set([...owner.requiredCapabilities, 'scene.camera2d.limits2d'])].sort();
  return plan;
}
test('bounded cameras use an opt-in outer helper and preserve unbounded camera and historical generated bytes', async t => {
  const plain = cameraProject(), old = await adapter.generate(plain), first = plain.scenes[0], second = plain.scenes[1];
  const plan = bounded(structuredClone(plain), 0, { mode: 'follow', targetInstanceId: first.actors[1].instanceId, offset: [700, -500], zoom: 2,
    limits: { left: -1000.5, top: -800.25, right: 1000.75, bottom: 800.5 } });
  cameraOn(plan, 1, { mode: 'fixed', center: [20, 50], zoom: .5 });
  const before = structuredClone(plan), generated = await adapter.generate(plan); assert.deepEqual(plan, before);
  assert.equal(generated.backend.version, '0.46.0'); assert.ok(generated.backend.capabilities.includes('scene.camera2d.limits2d'));
  assert.equal(adapter.descriptor.version, '0.46.0'); assert.ok(adapter.descriptor.capabilities.includes('scene.camera2d.limits2d'));
  assert.deepEqual(generated.sourceMap, old.sourceMap);
  for (const [name, bytes] of old.files) if (!name.startsWith('retry-') && !['project.godot', 'execution-clock-original.godot'].includes(name)) assert.deepEqual(generated.files.get(name), bytes, name);
  const base = JSON.parse(generated.files.get(`scenes/${first.scene.objectId}/camera2d.json`));
  assert.equal(base.schemaVersion, 1); assert.equal(Object.hasOwn(base.camera, 'limits'), false);
  assert.deepEqual(JSON.parse(generated.files.get(`scenes/${first.scene.objectId}/camera2d-limits.json`)), plan.scenes[0].camera2d.document);
  assert.equal(generated.files.has(`scenes/${second.scene.objectId}/camera2d-limits.json`), false);
  assert.match(generated.files.get(`scenes/${first.scene.objectId}/camera2d-main.tscn`).toString(), /camera2d-limits-scene\.gd/);
  assert.doesNotMatch(generated.files.get(`scenes/${second.scene.objectId}/camera2d-main.tscn`).toString(), /limits/);
  const directory = await cameraStage(t, generated), inventory = await validateGodotCamera2DInventory(directory);
  assert.deepEqual(inventory.scripts, ['camera2d-scene.gd', 'camera2d-project-runtime.gd', 'camera2d-limits-scene.gd']);
  assert.deepEqual(await adapter.generate(plan), generated);
});
test('bounded inventory rejects script drift, unpaired declarations, wrong target and limits or orphan sidecars', async t => {
  const plan = cameraProject(), id = plan.entrySceneId;
  bounded(plan, 0, { mode: 'follow', targetInstanceId: plan.scenes[0].actors[1].instanceId, offset: [200, -100], zoom: .125,
    limits: { left: -100, top: -100, right: 100, bottom: 100 } });
  const generated = await adapter.generate(plan), directory = await cameraStage(t, generated);
  for (const name of ['camera2d-limits-scene.gd', `scenes/${id}/camera2d-limits.json`, `scenes/${id}/camera2d.json`, `scenes/${id}/camera2d-main.tscn`]) {
    const file = path.join(directory, name), bytes = await fs.readFile(file); await fs.appendFile(file, '\n');
    await assert.rejects(validateGodotCamera2DInventory(directory), invalid, name); await fs.writeFile(file, bytes);
    await fs.rm(file); await assert.rejects(validateGodotCamera2DInventory(directory), invalid, name + ' missing'); await fs.writeFile(file, bytes);
  }
  const full = path.join(directory, `scenes/${id}/camera2d-limits.json`), original = await fs.readFile(full);
  for (const change of [doc => { doc.camera.offset[0]++; }, doc => { doc.camera.limits.right = doc.camera.limits.left; }, doc => { doc.schemaVersion = 1; }, doc => { doc.camera.targetInstanceId = 'ffffffff-1111-4111-8111-111111111111'; }]) {
    const doc = JSON.parse(original); change(doc); await fs.writeFile(full, JSON.stringify(doc, null, 2) + '\n');
    await assert.rejects(validateGodotCamera2DInventory(directory), invalid); await fs.writeFile(full, original);
  }
  const uid = path.join(directory, 'camera2d-limits-scene.gd.uid'); await fs.writeFile(uid, 'uid://good123\n'); assert.ok(await validateGodotCamera2DInventory(directory));
  await fs.writeFile(uid, 'unowned'); await assert.rejects(validateGodotCamera2DInventory(directory), invalid); await fs.rm(uid);
  const helper = path.join(directory, 'camera2d-limits-scene.gd'); await fs.rm(helper); await fs.symlink(path.join(directory, 'camera2d-scene.gd'), helper);
  await assert.rejects(validateGodotCamera2DInventory(directory), invalid); await fs.rm(helper); await fs.writeFile(helper, generated.files.get('camera2d-limits-scene.gd'));
  assert.ok(await validateGodotCamera2DInventory(directory));
});
test('unbounded projects neither generate nor admit a limits helper or v2 declaration', async t => {
  const plan = cameraOn(cameraProject(), 0, { mode: 'fixed', center: [30, 50], zoom: 1 }), generated = await adapter.generate(plan), directory = await cameraStage(t, generated);
  assert.equal(generated.backend.version, '0.46.0'); assert.equal(generated.backend.capabilities.includes('scene.camera2d.limits2d'), false);
  assert.equal([...generated.files.keys()].some(name => name.includes('camera2d-limits')), false);
  const file = path.join(directory, 'camera2d-limits-scene.gd'); await fs.writeFile(file, await fs.readFile(new URL('../backends/godot4/camera2d-limits-scene.gd', import.meta.url)));
  await assert.rejects(validateGodotCamera2DInventory(directory), invalid); await fs.rm(file);
  assert.ok(await validateGodotCamera2DInventory(directory));
});
