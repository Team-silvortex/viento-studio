import '../adapters/node-studio-core.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { scenePhysics2DDropThroughAuthor } from './helpers/scene-physics2d-drop-through-author-fixture.mjs';
import { captureBuildSnapshot } from '../adapters/node-build-snapshot.mjs';
import { generateGodotPhysicsMovementContactsProject } from '../backends/godot4-physics-movement-contacts.mjs';
import { generateGodotPhysicsOneWayProject } from '../backends/godot4-physics-one-way.mjs';
import { generateGodotPhysicsDropThroughProject, godotPhysicsDropThroughAssemblyScripts } from '../backends/godot4-physics-drop-through.mjs';

const invalid = { errorCode: 'build_physics_drop_through_invalid' };
const capability = 'physics.character-drop-through2d';
async function captured(f) {
  const captured = await captureBuildSnapshot(f.author, f.assemblyId);
  assert.equal(captured.ok, true, JSON.stringify(captured.diagnostics));
  return { ...f, plan: captured.plan, generated: await generateGodotPhysicsDropThroughProject(captured.plan) };
}
async function stage(f, generated = f.generated) {
  const directory = await fs.mkdtemp(path.join(f.temporary, 'drop-inventory-'));
  for (const [name, bytes] of generated.files) {
    await fs.mkdir(path.dirname(path.join(directory, name)), { recursive: true });
    await fs.writeFile(path.join(directory, name), bytes);
  }
  return directory;
}

test('drop generator extends only the shared hook and preserves all author protocols and previous generated bytes', async t => {
  const f = await captured(await scenePhysics2DDropThroughAuthor(t)), plan = structuredClone(f.plan);
  const old = await generateGodotPhysicsMovementContactsProject(f.plan);
  assert.equal(old.backend.version, '0.28.0'); assert.equal(f.generated.backend.version, '0.29.0');
  assert.equal(f.generated.backend.protocolVersion, old.backend.protocolVersion);
  assert.deepEqual(f.generated.sourceMap, old.sourceMap); assert.deepEqual(f.plan, plan);
  assert.ok(f.generated.backend.capabilities.includes(capability));
  for (const [name, bytes] of old.files) assert.deepEqual(f.generated.files.get(name === 'movement-contacts-helper.gd' ? 'movement-contacts-base-helper.gd' : name), bytes, name);
  const directory = await stage(f), inventory = await godotPhysicsDropThroughAssemblyScripts(directory);
  for (const name of f.generated.files.keys()) if (name.endsWith('.gd')) assert.ok(inventory.includes(name), name);
  assert.equal(new Set(inventory).size, inventory.length);
  await assert.rejects(generateGodotPhysicsDropThroughProject(f.plan.scenes[0]), { errorCode: 'build_physics_requires_project' });
});

for (const omit of ['platform', 'motor']) test(`drop generator without ${omit} keeps the complete frozen 0.28 result`, async t => {
  const f = await scenePhysics2DDropThroughAuthor(t);
  await f.edit(f.physicsPath, document => {
    for (const body of document.bodies) if (omit === 'platform') delete body.oneWay; else delete body.characterMotion;
  });
  const ready = await captured(f);
  assert.deepEqual(ready.generated, await generateGodotPhysicsMovementContactsProject(ready.plan));
  assert.ok(!ready.generated.backend.capabilities.includes(capability));
  assert.ok(await godotPhysicsDropThroughAssemblyScripts(await stage(ready)));
});

test('drop inventory rejects missing, redirected and substituted helpers and saved originals', async t => {
  const f = await captured(await scenePhysics2DDropThroughAuthor(t)), directory = await stage(f);
  for (const name of ['drop-through-project.json', 'drop-through-helper.gd', 'drop-through-port.gd', 'movement-contacts-base-helper.gd', 'movement-contacts-helper.gd']) {
    const file = path.join(directory, name), bytes = await fs.readFile(file);
    await fs.rm(file); await assert.rejects(godotPhysicsDropThroughAssemblyScripts(directory), invalid);
    await fs.symlink(path.join(f.author, f.physicsPath), file); await assert.rejects(godotPhysicsDropThroughAssemblyScripts(directory), invalid);
    await fs.rm(file);
    await fs.writeFile(file, Buffer.concat([bytes, Buffer.from(name.endsWith('.gd') ? '\n# substituted\n' : '\n{}')]));
    await assert.rejects(godotPhysicsDropThroughAssemblyScripts(directory), invalid);
    await fs.writeFile(file, bytes);
  }
  assert.ok(await godotPhysicsDropThroughAssemblyScripts(directory));
});

test('drop inventory validates exact selected scene membership and rejects orphan bridges in historical projects', async t => {
  const f = await captured(await scenePhysics2DDropThroughAuthor(t)), directory = await stage(f);
  const file = path.join(directory, 'drop-through-project.json'), bytes = await fs.readFile(file), manifest = JSON.parse(bytes);
  for (const value of [{ ...manifest, extra: true }, { ...manifest, schemaVersion: 2 }, { ...manifest, sceneIds: [] },
    { ...manifest, sceneIds: [f.sceneIds[1]] }, { ...manifest, sceneIds: [...manifest.sceneIds, ...manifest.sceneIds] }]) {
    await fs.writeFile(file, JSON.stringify(value)); await assert.rejects(godotPhysicsDropThroughAssemblyScripts(directory), invalid);
  }
  await fs.writeFile(file, bytes);
  for (const generator of [generateGodotPhysicsOneWayProject, generateGodotPhysicsMovementContactsProject]) {
    const previous = await generator(f.plan), legacy = await stage(f, previous);
    assert.ok(await godotPhysicsDropThroughAssemblyScripts(legacy));
    for (const name of ['drop-through-project.json', 'drop-through-helper.gd', 'drop-through-port.gd', 'movement-contacts-base-helper.gd']) {
      const orphan = path.join(legacy, name); await fs.writeFile(orphan, f.generated.files.get(name));
      await assert.rejects(godotPhysicsDropThroughAssemblyScripts(legacy), invalid); await fs.rm(orphan);
    }
    const bridge = path.join(legacy, 'movement-contacts-helper.gd'), original = previous.files.get('movement-contacts-helper.gd');
    await fs.writeFile(bridge, f.generated.files.get('movement-contacts-helper.gd'));
    await assert.rejects(godotPhysicsDropThroughAssemblyScripts(legacy), invalid);
    if (original) await fs.writeFile(bridge, original); else await fs.rm(bridge);
    assert.ok(await godotPhysicsDropThroughAssemblyScripts(legacy));
  }
});
