test('real Godot instances: shared definition and resource, independent movement, cold frozen run and protocol guard', {
  skip: !godot && 'Set VIENTO_GODOT_BIN to run real Godot instances', timeout: 120000,
}, async t => {
  const { root, temporary } = await fixture(t), before = await inventory(root), output = path.join(temporary, 'build');
  const built = await buildProject({ root, scene: sceneId, godot, output });
  assert.equal(built.ok, true, JSON.stringify(built));
  assert.equal(built.record.backend.protocolVersion, 2);
  assert.equal(built.record.artifact.files.filter(item => item.path.startsWith('images/')).length, 1);
  assert.deepEqual(await inventory(root), before);
  await fs.rename(root, `${root}-offline`);
  const run = await runProjectBuild({ buildDirectory: output, godot });
  assert.equal(run.ok, true, JSON.stringify(run));
  assert.deepEqual(run.record.events.filter(item => item.event === 'state').map(item => [item.instanceId, item.state]), [[first, 'moving'], [first, 'idle']]);
  const actors = run.record.events.find(item => item.event === 'finished').actors;
  assert.deepEqual(actors, [
    { instanceId: first, objectId: actorId, position: [240, 220], state: 'idle' },
    { instanceId: second, objectId: actorId, position: [420, 120], state: 'idle' },
  ]);
  assert.deepEqual(await inventory(`${root}-offline`), before);
  await assert.rejects(fs.stat(path.join(run.sessionDirectory, 'project')), { code: 'ENOENT' });
  const record = JSON.parse(await fs.readFile(path.join(output, 'build.json')));
  record.backend.protocolVersion = 1;
  await fs.writeFile(path.join(output, 'build.json'), JSON.stringify(record));
  const altered = await runProjectBuild({ buildDirectory: output, godot });
  assert.equal(altered.ok, false); assert.equal(altered.diagnostics[0].code, 'runtime_adapter_changed');
});
