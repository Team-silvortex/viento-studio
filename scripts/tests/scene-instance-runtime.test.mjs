test('instance generation gives repeated definitions stable distinct nodes and deduplicated resources', async () => {
  const value = plan(), before = structuredClone(value), generated = await generateGodotProject(value);
  assert.equal(generated.backend.protocolVersion, 2); assert.equal(generated.backend.version, '0.2.0');
  assert.notEqual(generated.backend.sha256, 'dba885d7965715e56b1f1ac394dc78e3227d3502d23318a736dca6eb93beabe6');
  const scene = JSON.parse(generated.files.get('scene.json'));
  assert.equal(scene.schemaVersion, 2);
  assert.deepEqual(scene.actors.map(actor => actor.instanceId), [first, second]);
  assert.equal(scene.actors[0].objectId, scene.actors[1].objectId);
  assert.equal(generated.imageFiles.size, 1);
  assert.equal(generated.sourceMap.schemaVersion, 2);
  assert.deepEqual(generated.sourceMap.objects.map(actor => actor.nodePath), [first, second].map(id => `/root/VientoScene/actor_${id.replaceAll('-', '_')}`));
  const reordered = await generateGodotProject({ ...value, actors: [...value.actors].reverse() });
  const byIdentity = output => Object.fromEntries(output.sourceMap.objects.map(actor => [actor.instanceId, actor.nodePath]));
  assert.deepEqual(byIdentity(reordered), byIdentity(generated));
  assert.deepEqual(value, before);
  assert.match(generated.files.get('runtime.gd').toString(), /set_meta\("viento_instance_id", actor\["instanceId"\]\)/);
});

test('instance protocol streams independently addressed state events and declaration diagnostics', () => {
  const value = plan(), observed = [], reader = createRuntimeEventReader(value, { onEvent: event => observed.push(event) });
  const ready = lifecycle(value), text = frame(ready);
  assert.deepEqual(reader.push(text.slice(0, 22)), []);
  assert.deepEqual(reader.push(text.slice(22)), [ready]);
  const moving = { protocol: 2, event: 'state', instanceId: first, objectId: value.actors[0].objectId, state: 'moving' };
  reader.push(frame(moving));
  reader.push(frame(diagnostic(value.actors[1])));
  const finished = { protocol: 2, event: 'finished', actors: value.actors.map(actorState).reverse(), fixedDelta: 0.25 };
  reader.push(frame(finished).trimEnd()); reader.finish(); reader.finish();
  assert.equal(observed.length, 4);
  assert.deepEqual(observed[1], moving);
  assert.equal(reader.diagnostics.length, 1);
  assert.equal(reader.diagnostics[0].instanceId, second);
  assert.equal(reader.diagnostics[0].relatedObjectId, value.actors[1].objectId);
  assert.equal(reader.diagnostics[0].objectId, value.scene.objectId);
  assert.equal(reader.diagnostics[0].sourcePath, value.scene.sourcePath);
  assert.equal(reader.diagnostics[0].propertyPath, '/actors/1');
});

test('instance protocol rejects missing, duplicate, mismatched, forged and legacy identities', () => {
  const value = plan(), ready = lifecycle(value), actor = value.actors[0];
  const invalid = frames => {
    const result = readRuntimeEvents({ stdout: frames.map(frame).join('') }, value);
    assert.ok(result.diagnostics.some(item => item.code === 'runtime_protocol_invalid'), JSON.stringify(frames));
  };
  for (const frames of [
    [{ ...ready, protocol: 1 }],
    [{ ...ready, actors: ready.actors.map(({ instanceId, ...item }) => item) }],
    [{ ...ready, actors: [ready.actors[0], ready.actors[0]] }],
    [{ ...ready, actors: [{ ...ready.actors[0], objectId: actorId }, ready.actors[1]] }],
    [ready, { protocol: 2, event: 'state', objectId: actor.objectId, state: 'moving' }],
    [ready, { protocol: 2, event: 'state', instanceId: first, objectId: actorId, state: 'moving' }],
    [ready, { protocol: 2, event: 'state', instanceId: 'unknown', objectId: actor.objectId, state: 'moving' }],
    [diagnostic(actor, { instanceId: undefined })],
    [diagnostic(actor, { objectId: actorId })],
    [diagnostic(actor, { sourcePath: '/outside' })],
    [diagnostic(actor, { resourceId: 'unknown' })],
    [diagnostic(actor, { instanceId: undefined, objectId: value.scene.objectId, resourceId: imageId })],
    [ready, ready],
    [{ protocol: 2, event: 'finished', actors: ready.actors, fixedDelta: 0.25 }],
    [ready, { protocol: 2, event: 'finished', actors: ready.actors, fixedDelta: 0.25 }, diagnostic(actor)],
  ]) invalid(frames);
  const changed = structuredClone(value); changed.actors[1].imageResourceId = null;
  assert.equal(readRuntimeEvents({ stdout: frame(diagnostic(changed.actors[1], { resourceId: imageId })) }, changed).diagnostics[0].code, 'runtime_protocol_invalid');
});

test('instance image failures resolve trusted field locations and report every affected instance', () => {
  const value = plan();
  value.actors.forEach((actor, index) => { actor.fieldSources.imageResourceId = { ...actor.declaration, propertyPath: `/actors/${index}/imageResourceId` }; });
  const result = readRuntimeEvents({ stdout: frame(diagnostic(value.actors[1], { code: 'runtime_image_failed', resourceId: imageId })) }, value);
  assert.equal(result.diagnostics[0].propertyPath, '/actors/1/imageResourceId');
  assert.equal(result.diagnostics[0].instanceId, second);
  const imported = godotDiagnostics({ status: 'failed', stdout: '', stderr: `ERROR: Cannot import ${imageId}` }, value);
  assert.deepEqual(imported.filter(item => item.code === 'godot_error').map(item => item.instanceId), [first, second]);
  assert.deepEqual(imported.filter(item => item.code === 'godot_error').map(item => item.propertyPath), ['/actors/0/imageResourceId', '/actors/1/imageResourceId']);
});

test('instance import diagnostics bound repeated shared-resource errors and oversized messages', () => {
  const value = plan(), base = value.actors[0];
  value.actors = Array.from({ length: 128 }, (_, index) => ({ ...structuredClone(base), instanceId: `instance-${index}`,
    declaration: { ...base.declaration, propertyPath: `/actors/${index}` } }));
  const line = `ERROR: Cannot import ${imageId} ${'x'.repeat(16000)}`;
  for (const status of ['succeeded', 'failed']) {
    const diagnostics = godotDiagnostics({ status, stdout: '', stderr: Array.from({ length: 100 }, () => line).join('\n') }, value);
    assert.equal(diagnostics.length, 256);
    assert.deepEqual(diagnostics.slice(0, 128).map(item => item.instanceId), value.actors.map(item => item.instanceId));
    assert.ok(diagnostics.every(item => item.message.length <= 4096));
    if (status === 'failed') assert.equal(diagnostics.at(-1).code, 'build_process_failed');
    else assert.equal(diagnostics.at(-1).code, 'godot_error');
  }
});

